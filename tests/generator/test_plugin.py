class ErrorTest(unittest.TestCase):
    def test_proto2(self):
        self.assertIn("a.proto: only proto3 files are supported",
                      error('syntax = "proto2"; message m { optional int32 a = 1; }'))

    def test_map(self):
        self.assertIn("a.proto: m.values: map fields are not supported",
                      error(PROTO3 + "message m { map<string, int32> values = 1; }"))

    def test_repeated_without_max_count(self):
        text = error(PROTO3 + "package p; message m { repeated int32 a = 1; }")
        self.assertIn("a.proto: p.m.a: a repeated field needs a capacity. "
                      "Add this line to a.options: p.m.a max_count:<N>", text)

    def test_repeated_without_max_count_says_when_no_options_file_was_found(self):
        hint = "No file a.options was found. If it is in another folder, use --micropb_opt=options_dir=<folder>."
        proto = PROTO3 + "message m { repeated int32 a = 1; repeated int32 b = 2; }"
        self.assertIn("m.a max_count:<N>. " + hint, error(proto))
        self.assertNotIn("was found", error(proto, "m.b max_count:2\n"))

    def test_fixed_count_without_max_count(self):
        self.assertIn("a repeated field needs a capacity",
                      error(PROTO3 + "message m { repeated int32 a = 1; }", "m.a fixed_count:true\n"))

    def test_fixed_length_without_max_size(self):
        self.assertIn("a.proto: m.a: fixed_length needs max_size",
                      error(PROTO3 + "message m { bytes a = 1; }", "m.a fixed_length:true\n"))

    def test_message_that_contains_itself(self):
        self.assertIn("a.proto: a message cannot contain itself: node -> node",
                      error(PROTO3 + "message node { optional node next = 1; }"))

    def test_messages_that_contain_each_other(self):
        text = error(PROTO3 + "message a { b x = 1; } message b { oneof v { c x = 1; } } message c { repeated a x = 1; }",
                     "* max_count:2\n")
        self.assertIn("a.proto: a message cannot contain itself: a -> b -> c -> a", text)

    def test_oneof_with_two_members_of_one_type(self):
        self.assertIn("a.proto: m.v: a oneof cannot have two members of the type std::int32_t",
                      error(PROTO3 + "message m { oneof v { int32 a = 1; int32 b = 2; } }"))

    def test_two_types_with_the_same_flat_name(self):
        self.assertIn("a.proto: two types have the C++ name A_B",
                      error(PROTO3 + "message A_B {} message A { message B {} }"))

    def test_int_size_8_on_a_repeated_unsigned_field(self):
        text = error(PROTO3 + "message m { repeated uint32 a = 1; }", "m.a max_count:4 int_size:IS_8\n")
        self.assertIn("a.proto: m.a: int_size:IS_8 on a repeated unsigned field gives a bytes field", text)

    def test_bad_options_lines(self):
        proto = PROTO3 + "message m { repeated int32 a = 1; }"
        cases = {
            "m.a max_count\n": "a.options:1: expected <name pattern> <option>:<value> ...",
            "\nm.a max_count:4 fixed_count\n": "a.options:2: expected <name pattern> <option>:<value> ...",
            "m.a max_count:x\n": "a.options:1: max_count needs a number above 0",
            "m.a max_count:0\n": "a.options:1: max_count needs a number above 0",
            "m.a max_size:-1\n": "a.options:1: max_size needs a number above 0",
            "m.a max_count:4 fixed_count:maybe\n": "a.options:1: fixed_count needs true or false",
            "m.a max_count:4 int_size:IS_12\n": "a.options:1: int_size needs IS_8, IS_16, IS_32 or IS_64",
        }
        for options, expected in cases.items():
            with self.subTest(options=options):
                self.assertIn(expected, error(proto, options))

    def test_unknown_parameter(self):
        result = run({"a.proto": PROTO3 + "message m {}"}, "--micropb_opt=speed=fast")
        self.assertNotEqual(result.rc, 0)
        self.assertIn("unknown parameter 'speed=fast'", result.stderr)

    def test_error_in_one_file_writes_no_header(self):
        result = run({"a.proto": PROTO3 + "message m {}", "b.proto": 'syntax = "proto2"; message n {}'})
        self.assertNotEqual(result.rc, 0)
        self.assertEqual(result.headers, {})


class WarningTest(unittest.TestCase):
    def warnings(self, proto, options):
        result = run({"a.proto": PROTO3 + proto, "a.options": options})
        self.assertEqual(result.rc, 0, result.stderr)
        return result.stderr, result.headers["a.pb.hpp"]

    def test_unknown_option(self):
        stderr, text = self.warnings("message m { repeated int32 a = 1; }", "m.a max_count:4 type:FT_POINTER\n")
        self.assertIn("a.options:1: warning: the unknown option 'type' is ignored", stderr)
        self.assertEqual(members(text, "m"), ["pb::repeated<std::int32_t, 4> a;"])

    def test_option_that_does_not_apply(self):
        stderr, text = self.warnings("package p; message m { string name = 1; int32 a = 2; sint32 b = 3; }",
                                     "m.name max_size:40\n\nm.a max_count:4\nm.b int_size:IS_8\n")
        self.assertIn("a.options:1: warning: max_size does not apply to p.m.name", stderr)
        self.assertIn("a.options:3: warning: max_count does not apply to p.m.a", stderr)
        self.assertIn("a.options:4: warning: int_size does not apply to p.m.b", stderr)
        self.assertEqual(members(text, "m"), ["std::string_view name;", "std::int32_t a;", "pb::sint32 b;"])

    def test_max_size_does_not_apply_to_repeated_bytes(self):
        stderr, text = self.warnings("message m { repeated bytes a = 1; }", "m.a max_count:2 max_size:8\n")
        self.assertIn("a.options:1: warning: max_size does not apply to m.a", stderr)

    def test_wildcard_rule_gives_no_warning(self):
        stderr, _ = self.warnings("message m { string name = 1; int32 a = 2; repeated int32 b = 3; bytes c = 4; }",
                                  "* max_count:8 max_size:16 int_size:IS_16\n")
        self.assertEqual(stderr, "")

    def test_pattern_that_matches_no_field(self):
        stderr, _ = self.warnings("message m { bool a = 1; }", "m.typo max_count:4\n")
        self.assertIn("a.options:1: warning: 'm.typo' matches no field", stderr)

    def test_no_warning_without_a_reason(self):
        stderr, _ = self.warnings("message m { repeated int32 a = 1; bytes b = 2; }",
                                  "m.a max_count:4 fixed_count:true\nm.b max_size:6 fixed_length:true\n")
        self.assertEqual(stderr, "")


class CheckedInTest(unittest.TestCase):
    """The generated headers that the C++ test `test_generated` compiles."""

    # The folder to run protoc in, the folder of the headers, the .proto files, more protoc arguments.
    GENERATED = [
        (REPO / "tests/vectors", REPO / "tests/vectors", ["vectors.proto"], []),
        (REPO, REPO / "tests/generator", ["features.proto", "shared.proto"],
         ["-Itests/generator", "--micropb_opt=options_dir=tests/generator"]),
    ]

    def test_checked_in_headers_are_current(self):
        for cwd, folder, protos, args in self.GENERATED:
            with tempfile.TemporaryDirectory() as out:
                rc, stderr = run_protoc(cwd, protos, out, *args)
                self.assertEqual((rc, stderr), (0, ""))
                for proto in protos:
                    name = proto.replace(".proto", ".pb.hpp")
                    text = (Path(out) / name).read_text()
                    if os.environ.get("MICROPB_UPDATE_GENERATED"):
                        (folder / name).write_text(text, newline="\n")
                    with self.subTest(header=name):
                        self.assertTrue((folder / name).is_file(), "run again with MICROPB_UPDATE_GENERATED=1")
                        self.assertEqual(text, (folder / name).read_text(),
                                         "run again with MICROPB_UPDATE_GENERATED=1")


