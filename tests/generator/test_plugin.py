class WarningTest(unittest.TestCase):
    def warnings(self, proto, options):
        result = run({"a.proto": PROTO3 + proto, "a.options": options})
        self.assertEqual(result.rc, 0, result.stderr)
        return result.stderr, result.headers["a.pb.hpp"]

    def test_enum_intsize_on_a_field(self):
        stderr, _ = self.warnings("message m { int32 a = 1; }", "m.a enum_intsize:IS_8\n")
        self.assertIn("a.options:1: warning: enum_intsize does not apply to m.a", stderr)

    def test_enum_rule_is_not_a_rule_without_a_match(self):
        stderr, text = self.warnings("enum E { E_A = 0; }", "E enum_intsize:IS_8\n")
        self.assertNotIn("matches no field", stderr)
        self.assertIn("int8_t", text)

    def test_unknown_option(self):
        stderr, text = self.warnings("message m { repeated int32 a = 1; }", "m.a max_count:4 anonymous_oneof:true\n")
        self.assertIn("a.options:1: warning: the unknown option 'anonymous_oneof' is ignored", stderr)
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 4> a = {};"])

    def test_option_that_does_not_apply(self):
        stderr, text = self.warnings("package p; message m { string name = 1; int32 a = 2; fixed32 b = 3; bytes c = 4; }",
                                     "m.name fixed_length:true\n\nm.a max_count:4\nm.b int_size:IS_8\nm.c max_length:8\n")
        self.assertIn("a.options:1: warning: fixed_length does not apply to p.m.name", stderr)
        self.assertIn("a.options:3: warning: max_count does not apply to p.m.a", stderr)
        self.assertIn("a.options:4: warning: int_size does not apply to p.m.b", stderr)
        self.assertIn("a.options:5: warning: max_length does not apply to p.m.c", stderr)
        self.assertEqual(members(text, "m"),
                         ["std::string_view name = {};", "int32_t a = 0;", "uint32_t b = 0;", "std::span<const uint8_t> c = {};"])

    def test_int_size_does_not_apply_to_fixed_and_enum_fields(self):
        stderr, text = self.warnings("enum e { E_A = 0; } message m { sfixed32 a = 1; e b = 2; fixed64 c = 3; }",
                                     "m.a int_size:IS_8\nm.b int_size:IS_16\nm.c int_size:IS_32\n")
        for name in "abc":
            self.assertIn(f"warning: int_size does not apply to m.{name}", stderr)
        self.assertEqual(members(text, "m"), ["int32_t a = 0;", "e b = e::A;", "uint64_t c = 0;"])

    def test_pointer_ignores_the_sizes(self):
        stderr, text = self.warnings("message m { repeated int32 a = 1; bytes b = 2; string c = 3; }",
                                     "m.a max_count:4 fixed_count:true type:FT_POINTER\n"
                                     "m.b max_size:8 type:FT_POINTER\n"
                                     "m.c max_length:8 type:FT_POINTER\n")
        self.assertIn("a.options:1: warning: max_count does not apply to m.a", stderr)
        self.assertIn("a.options:1: warning: fixed_count does not apply to m.a", stderr)
        self.assertIn("a.options:2: warning: max_size does not apply to m.b", stderr)
        self.assertIn("a.options:3: warning: max_length does not apply to m.c", stderr)
        self.assertEqual(members(text, "m"),
                         ["std::span<const int32_t> a = {};", "std::span<const uint8_t> b = {};", "std::string_view c = {};"])

    def test_type_does_not_apply_to_a_scalar(self):
        stderr, text = self.warnings("message m { int32 a = 1; }", "m.a type:FT_POINTER\n")
        self.assertIn("a.options:1: warning: type does not apply to m.a", stderr)
        self.assertEqual(members(text, "m"), ["int32_t a = 0;"])

    def test_wildcard_rule_gives_no_warning(self):
        stderr, _ = self.warnings("message m { string name = 1; int32 a = 2; repeated int32 b = 3; bytes c = 4; }",
                                  "* max_count:8 max_size:16 int_size:IS_16\n")
        self.assertEqual(stderr, "")

    def test_pattern_that_matches_no_field(self):
        stderr, _ = self.warnings("message m { bool a = 1; }", "m.typo max_count:4\n")
        self.assertIn("a.options:1: warning: 'm.typo' matches no field", stderr)

    def test_question_mark_is_a_wildcard(self):
        stderr, text = self.warnings("message m { string s = 1; repeated int32 a = 2; }", "m.? max_count:5\n")
        self.assertEqual(stderr, "")
        self.assertEqual(members(text, "m"), ["std::string_view s = {};", "pb::repeated<int32_t, 5> a = {};"])

    def test_options_file_with_a_byte_order_mark(self):
        stderr, text = self.warnings("message m { repeated int32 a = 1; }", "\ufeffm.a max_count:4\n")
        self.assertEqual(stderr, "")
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 4> a = {};"])

    def test_warnings_are_printed_also_when_an_error_follows(self):
        proto = PROTO3 + "message m { repeated int32 a = 1; bytes b = 2; }"
        text = error(proto, "m.a max_cout:4\nm.b fixed_length:true\n")
        self.assertIn("a.options:1: warning: the unknown option 'max_cout' is ignored", text)
        self.assertIn("m.b: fixed_length needs max_size", text)
        text = error(proto, "m.aa max_count:4\nm.b fixed_length:true\n")
        self.assertIn("a.options:1: warning: 'm.aa' matches no field", text)
        self.assertNotIn("'m.b' matches no field", text)

    def test_options_file_of_the_current_folder_comes_first(self):
        result = run({"a.proto": PROTO3 + "message m { repeated int32 a = 1; }", "a.options": "m.a max_count:1\n",
                      "opts/a.options": "m.a max_count:2\n"}, "--micropb_opt=options_dir=opts")
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(members(result.headers["a.pb.hpp"], "m"), ["pb::repeated<int32_t, 1> a = {};"])

    def test_no_warning_without_a_reason(self):
        stderr, _ = self.warnings("message m { repeated int32 a = 1; bytes b = 2; }",
                                  "m.a max_count:4 fixed_count:true\nm.b max_size:6 fixed_length:true\n")
        self.assertEqual(stderr, "")


class CheckedInTest(unittest.TestCase):
    """The generated headers that the C++ test `test_generated` compiles."""

    # The folder to run protoc in, the folder of the headers, the .proto files, more protoc arguments.
    GENERATED = [
        (REPO / "tests/vectors", REPO / "tests/vectors", ["vectors.proto"], []),
        (REPO, REPO / "tests/generator", ["features.proto", "shared.proto", "detail.proto"],
         ["-Itests/generator", "--micropb_opt=options_dir=tests/generator"]),
    ]

    def test_checked_in_headers_are_current(self):
        for cwd, folder, protos, args in self.GENERATED:
            with tempfile.TemporaryDirectory() as out:
                rc, stderr = run_protoc(cwd, protos, out, *args)
                self.assertEqual((rc, stderr), (0, ""))
                for proto in protos:
                    name = proto.replace(".proto", ".pb.hpp")
                    text = (Path(out) / name).read_text()
                    if os.environ.get("MICROPB_UPDATE_GENERATED"):
                        (folder / name).write_text(text, newline="\n")
                    with self.subTest(header=name):
                        self.assertTrue((folder / name).is_file(), "run again with MICROPB_UPDATE_GENERATED=1")
                        self.assertEqual(text, (folder / name).read_text(),
                                         "run again with MICROPB_UPDATE_GENERATED=1")


