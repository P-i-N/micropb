#!/usr/bin/env python3
"""Tests of tools/protoc-gen-micropb.py. Each test runs the plugin through protoc.

    python tests/generator/test_plugin.py                 run the tests
    python tests/generator/test_plugin.py --check-tools   return 0 when protoc is available

protoc comes from the environment variable PROTOC, from PATH, or from the Python module grpc_tools.
MICROPB_UPDATE_GENERATED=1 writes the checked-in headers again.
"""

import importlib.util
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path
from typing import NamedTuple

REPO = Path(__file__).resolve().parents[2]
PLUGIN = REPO / "tools" / "protoc-gen-micropb.py"


def protoc_command():
    """The command that starts protoc, or None."""
    if os.environ.get("PROTOC"):
        return [os.environ["PROTOC"]]
    if shutil.which("protoc"):
        return ["protoc"]
    if importlib.util.find_spec("grpc_tools"):
        return [sys.executable, "-m", "grpc_tools.protoc"]
    return None


def tools_available():
    return protoc_command() is not None


class Result(NamedTuple):
    rc: int
    headers: dict  # relative path -> text
    stderr: str


def make_starter(folder):
    """protoc needs an executable file. This one starts the plugin with the Python of the tests. `-S` removes the
    installed packages, so the plugin can use only the standard library."""
    if os.name == "nt":
        starter = Path(folder) / "protoc-gen-micropb.bat"
        starter.write_text(f'@"{sys.executable}" -S "{PLUGIN}" %*\n')
    else:
        starter = Path(folder) / "protoc-gen-micropb"
        starter.write_text(f'#!/bin/sh\nexec "{sys.executable}" -S "{PLUGIN}" "$@"\n')
        starter.chmod(starter.stat().st_mode | stat.S_IXUSR)
    return starter


def run_protoc(cwd, protos, out, *args):
    """Runs protoc with the plugin in `cwd`. Returns the return code and stderr."""
    if not any(arg.startswith("-I") for arg in args):
        args = ("-I.",) + args  # the default of protoc. The grpc_tools module does not have it.
    with tempfile.TemporaryDirectory() as bin_dir:
        command = protoc_command() + [f"--plugin=protoc-gen-micropb={make_starter(bin_dir)}", f"--micropb_out={out}"]
        done = subprocess.run(command + list(args) + list(protos), cwd=cwd, capture_output=True, text=True)
    return done.returncode, done.stderr


def run(files, *args, protos=None):
    """Writes `files` (name -> text) to a new folder and compiles `protos` (default: each .proto file) there."""
    with tempfile.TemporaryDirectory() as work:
        for name, text in files.items():
            path = Path(work) / name
            path.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(text, bytes):
                path.write_bytes(text)
            else:
                path.write_text(textwrap.dedent(text), encoding="utf-8")
        out = Path(work) / "out"
        out.mkdir()
        protos = protos or [name for name in files if name.endswith(".proto")]
        rc, stderr = run_protoc(work, protos, out, *args)
        headers = {p.relative_to(out).as_posix(): p.read_text() for p in out.rglob("*") if p.is_file()}
    return Result(rc, headers, stderr)


def header(proto, options=None, *args):
    """The header text for one proto3 file `a.proto` with the body `proto`."""
    files = {"a.proto": 'syntax = "proto3";\n' + textwrap.dedent(proto)}
    if options is not None:
        files["a.options"] = options
    result = run(files, *args)
    assert result.rc == 0 and "warning" not in result.stderr, result.stderr
    return result.headers["a.pb.hpp"]


def error(proto, options=None):
    """The error text of protoc for one file `a.proto` with the complete text `proto`. No header is written."""
    files = {"a.proto": textwrap.dedent(proto)}
    if options is not None:
        files["a.options"] = options
    result = run(files)
    assert result.rc != 0, "protoc did not fail"
    assert not result.headers, "a header was written"
    return result.stderr


class CoreTest(unittest.TestCase):
    def test_complete_header(self):
        text = header("""
            package app.link;
            enum Mode { MODE_OFF = 0; MODE_ON = 1; }
            message Inner { int32 x = 1; }
            message Outer { Inner child = 1; Mode mode = 2; string name = 3; bytes data = 4; sint32 delta = 5; }
            """)
        self.assertEqual(text, textwrap.dedent("""\
            // Generated by protoc-gen-micropb from a.proto. Do not edit.
            #pragma once

            #include <optional>
            #include <span>
            #include <stddef.h>
            #include <stdint.h>
            #include <string_view>

            #include <micropb/schema.hpp>

            namespace app::link {

            enum class Mode : int32_t {
                OFF = 0,
                ON = 1,
            };

            struct Inner {
                int32_t x = 0;
            };

            struct Outer {
                pb::optional<Inner> child = std::nullopt;
                Mode mode = Mode::OFF;
                std::string_view name = {};
                std::span<const uint8_t> data = {};
                int32_t delta = 0;
            };

            } // namespace app::link

            // Enum traits.

            template <>
            struct pb::traits<::app::link::Mode> {
                static constexpr ::app::link::Mode min = ::app::link::Mode::OFF;
                static constexpr ::app::link::Mode max = ::app::link::Mode::ON;
            };

            // Field lists.

            template <>
            struct pb::fields_of<::app::link::Inner> : pb::field_list<::app::link::Inner,
                pb::field_at<decltype(::app::link::Inner::x), 1, offsetof(::app::link::Inner, x)>> {};

            template <>
            struct pb::fields_of<::app::link::Outer> : pb::field_list<::app::link::Outer,
                pb::field_at<decltype(::app::link::Outer::child), 1, offsetof(::app::link::Outer, child)>,
                pb::field_at<decltype(::app::link::Outer::mode), 2, offsetof(::app::link::Outer, mode)>,
                pb::field_at<decltype(::app::link::Outer::name), 3, offsetof(::app::link::Outer, name)>,
                pb::field_at<decltype(::app::link::Outer::data), 4, offsetof(::app::link::Outer, data)>,
                pb::field_at<decltype(::app::link::Outer::delta), 5, offsetof(::app::link::Outer, delta), 0, pb::int_encoding::ZIGZAG>> {};

            // Message traits.

            template <>
            struct pb::traits<::app::link::Inner> : pb::detail::message_traits<::app::link::Inner> {
                static constexpr uint32_t x_tag = 1;
            };

            template <>
            struct pb::traits<::app::link::Outer> : pb::detail::message_traits<::app::link::Outer> {
                static constexpr uint32_t child_tag = 1;
                static constexpr uint32_t mode_tag = 2;
                static constexpr uint32_t name_tag = 3;
                static constexpr uint32_t data_tag = 4;
                static constexpr uint32_t delta_tag = 5;
            };
            """))

    def test_scalar_types(self):
        text = header("""
            message m {
              int32 a = 1; int64 b = 2; uint32 c = 3; uint64 d = 4; sint32 e = 5; sint64 f = 6; bool g = 7;
              float h = 8; double i = 9; fixed32 j = 10; fixed64 k = 11; sfixed32 l = 12; sfixed64 n = 13;
            }
            """)
        self.assertEqual(members(text, "m"), [
            "int32_t a = 0;", "int64_t b = 0;", "uint32_t c = 0;", "uint64_t d = 0;", "int32_t e = 0;",
            "int64_t f = 0;", "bool g = false;", "float h = 0.0f;", "double i = 0.0;", "uint32_t j = 0;",
            "uint64_t k = 0;", "int32_t l = 0;", "int64_t n = 0;"])
        self.assertEqual(field_list(text, "m"), [
            "a = 1", "b = 2", "c = 3", "d = 4", "e = 5:ZIGZAG", "f = 6:ZIGZAG", "g = 7",
            "h = 8", "i = 9", "j = 10:FIXED", "k = 11:FIXED", "l = 12:FIXED", "n = 13:FIXED"])

    def test_no_package_has_no_namespace(self):
        text = header("message m { bool a = 1; }")
        self.assertNotIn("namespace", text)
        self.assertIn("\n\nstruct m {\n    bool a = false;\n};\n\n// Field lists", text)
        self.assertEqual(field_list(text, "m"), ["a = 1"])
        self.assertEqual(traits(text, "m"), ["static constexpr uint32_t a_tag = 1;"])

    def test_includes_only_what_the_header_uses(self):
        text = header("message m {}")
        self.assertEqual(includes(text), ["<micropb/schema.hpp>"])
        text = header("message m { bool a = 1; }")
        self.assertEqual(includes(text), ["<stddef.h>", "<stdint.h>", "<micropb/schema.hpp>"])
        text = header("enum e { E_A = 0; }")
        self.assertEqual(includes(text), ["<stdint.h>", "<micropb/schema.hpp>"])
        self.assertNotIn("Field lists", text)

    def test_empty_message(self):
        text = header("message m {}")
        self.assertIn("struct m {};\n", text)
        self.assertIn("template <>\nstruct pb::fields_of<::m> : pb::field_list<::m> {};\n", text)

    def test_enum_prefix_from_camel_case_name(self):
        text = header("enum RxMode { RX_MODE_FIXED = 0; RX_MODE_VARIABLE = -1; }")
        self.assertIn("enum class RxMode : int32_t {\n    FIXED = 0,\n    VARIABLE = -1,\n};", text)

    def test_enum_keeps_names_when_a_value_has_no_prefix(self):
        text = header("enum color { COLOR_RED = 0; BLUE = 1; } message m { color c = 1; optional color opt = 2; }")
        self.assertIn("    COLOR_RED = 0,\n    BLUE = 1,\n", text)
        self.assertEqual(members(text, "m"), ["color c = color::COLOR_RED;", "pb::optional<color> opt = std::nullopt;"])

    def test_enum_keeps_names_when_the_rest_is_not_an_identifier(self):
        text = header("enum size { SIZE_8 = 0; SIZE_16 = 1; }")
        self.assertIn("    SIZE_8 = 0,\n    SIZE_16 = 1,\n", text)

    def test_limits_of_numbers(self):
        text = header("enum e { E_MIN = 0; E_LOW = -2147483648; E_HIGH = 2147483647; } message m { e a = 536870911; }")
        self.assertIn("    MIN = 0,\n    LOW = -2147483648,\n    HIGH = 2147483647,\n", text)
        self.assertEqual(field_list(text, "m"), ["a = 536870911"])

    def test_field_tags(self):
        text = header("""
            message m {
              int32 class = 1;
              optional bool flag = 10;
              oneof payload {
                string err = 20;
                uint32 code = 536870911;
              }
            }
            """)
        self.assertEqual(traits(text, "m"), [
            "static constexpr uint32_t class_tag = 1;",
            "static constexpr uint32_t flag_tag = 10;",
            "static constexpr uint32_t err_tag = 20;",
            "static constexpr uint32_t code_tag = 536870911;",
            "static constexpr size_t payload_err = 1;",
            "static constexpr size_t payload_code = 2;",
        ])

    def test_enum_traits_min_max(self):
        text = header("""
            package p;
            enum Unsorted { UNSORTED_ZERO = 0; UNSORTED_HIGH = 10; UNSORTED_NEG = -5; UNSORTED_MID = 3; }
            enum Single { SINGLE_ONLY = 0; }
            enum Aliased { option allow_alias = true; A_ZERO = 0; A_MIN = -2; A_MIN_DUP = -2; A_MAX = 7; A_MAX_DUP = 7; }
            message M { enum Nested { NESTED_A = 0; NESTED_B = 2; } Nested n = 1; }
            """)
        self.assertIn(textwrap.dedent("""\
            template <>
            struct pb::traits<::p::Unsorted> {
                static constexpr ::p::Unsorted min = ::p::Unsorted::NEG;
                static constexpr ::p::Unsorted max = ::p::Unsorted::HIGH;
            };"""), text)
        self.assertIn(textwrap.dedent("""\
            template <>
            struct pb::traits<::p::Single> {
                static constexpr ::p::Single min = ::p::Single::ONLY;
                static constexpr ::p::Single max = ::p::Single::ONLY;
            };"""), text)
        self.assertIn(textwrap.dedent("""\
            template <>
            struct pb::traits<::p::Aliased> {
                static constexpr ::p::Aliased min = ::p::Aliased::A_MIN;
                static constexpr ::p::Aliased max = ::p::Aliased::A_MAX;
            };"""), text)
        self.assertIn(textwrap.dedent("""\
            template <>
            struct pb::traits<::p::M_Nested> {
                static constexpr ::p::M_Nested min = ::p::M_Nested::A;
                static constexpr ::p::M_Nested max = ::p::M_Nested::B;
            };"""), text)

    def test_output_is_next_to_the_proto_path(self):
        result = run({"sub/dir/b.proto": 'syntax = "proto3"; message m {}'})
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(list(result.headers), ["sub/dir/b.pb.hpp"])
        self.assertTrue(result.headers["sub/dir/b.pb.hpp"].startswith(
            "// Generated by protoc-gen-micropb from sub/dir/b.proto. Do not edit.\n"))


def members(text, name):
    """The member lines of the struct `name` in the header `text`."""
    return [line.strip() for line in text.split(f"struct {name} {{\n")[1].split("\n};")[0].splitlines()]


def traits(text, name):
    """The constant lines of `pb::traits<::name>` in the header `text`."""
    full = "::" + name
    head = f"struct pb::traits<{full}> : pb::detail::message_traits<{full}> {{\n"
    return [line.strip() for line in text.split(head)[1].split("\n};")[0].splitlines()]


def field_list(text, name):
    """The entries of the field list of the type `name` in the header `text`, each as `<member> = <number>`.
    An alternative of a oneof has `/<index>` after the number; a non-varint integer has `:<encoding>`."""
    name = "::" + name  # the full name: the text is in the scope of `pb`, which has names of its own
    block = text.split(f"struct pb::fields_of<{name}> : pb::field_list<{name}")[1].split("{};")[0]
    entry = (rf"pb::field_at<decltype\({name}::(\w+)\), (\d+), offsetof\({name}, (\w+)\)"
             rf"(?:, (\d+)(?:, pb::int_encoding::(\w+))?)?>")
    assert block.count("pb::field_at<") == len(re.findall(entry, block)), block
    return [f"{member} = {number}" + (f"/{index}" if index and index != "0" else "") + (f":{enc}" if enc else "")
            for member, number, same, index, enc in re.findall(entry, block) if member == same]


def includes(text):
    """The names of the headers that the header `text` includes, in order."""
    return [line.split()[1] for line in text.splitlines() if line.startswith("#include")]


def definitions(text):
    """The names of the enums and structs of the header `text`, in order."""
    return re.findall(r"^(?:struct|enum class) (\w+)(?= [{:])", text, re.M)


class OptionsTest(unittest.TestCase):
    def test_max_count(self):
        text = header("message m { repeated int32 a = 1; }", "m.a max_count:4\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 4> a = {};"])

    def test_fixed_count(self):
        text = header("message m { repeated float a = 1; }", "m.a max_count:3 fixed_count:true\n")
        self.assertEqual(members(text, "m"), ["std::array<float, 3> a = {};"])
        self.assertIn("#include <array>\n", text)

    def test_fixed_count_false(self):
        text = header("message m { repeated float a = 1; }", "m.a max_count:3 fixed_count:false\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<float, 3> a = {};"])

    def test_max_size_and_fixed_length(self):
        text = header("message m { bytes a = 1; bytes b = 2; bytes c = 3; }",
                      "m.a max_size:16\nm.b max_size:6 fixed_length:true\n")
        self.assertEqual(members(text, "m"), [
            "pb::bytes<16> a = {};", "std::array<uint8_t, 6> b = {};", "std::span<const uint8_t> c = {};"])

    def test_string_max_length_and_max_size(self):
        text = header("message m { string a = 1; string b = 2; string c = 3; string d = 4; }",
                      "m.a max_length:15\nm.b max_size:16\nm.c max_size:1\n")
        self.assertEqual(members(text, "m"), [
            "pb::string<15> a = {};", "pb::string<15> b = {};", "pb::string<0> c = {};", "std::string_view d = {};"])

    def test_string_max_length_and_max_size_override_across_lines(self):
        text = header("message m { string a = 1; string b = 2; }",
                      "* max_size:32\nm.a max_length:10\n")
        self.assertEqual(members(text, "m"), ["pb::string<10> a = {};", "pb::string<31> b = {};"])
        text = header("message m { string a = 1; }", "m.a max_length:10\n* max_size:32\n")
        self.assertEqual(members(text, "m"), ["pb::string<31> a = {};"])

    def test_repeated_sized_bytes_and_strings(self):
        text = header("message m { repeated bytes a = 1; repeated string b = 2; }",
                      "m.a max_count:2 max_size:8\nm.b max_count:3 max_length:12\n")
        self.assertEqual(members(text, "m"), [
            "pb::repeated<pb::bytes<8>, 2> a = {};", "pb::repeated<pb::string<12>, 3> b = {};"])

    def test_int_size(self):
        text = header("message m { int32 a = 1; uint32 b = 2; int64 c = 3; uint64 d = 4; }",
                      "m.a int_size:IS_8\nm.b int_size:IS_16\nm.c int_size:IS_32\nm.d int_size:IS_64\n")
        self.assertEqual(members(text, "m"),
                         ["int8_t a = 0;", "uint16_t b = 0;", "int32_t c = 0;", "uint64_t d = 0;"])

    def test_int_size_on_sint(self):
        text = header("message m { sint32 a = 1; sint32 b = 2; sint64 c = 3; sint32 d = 4; sint64 e = 5; }",
                      "m.a int_size:IS_8\n" "m.b int_size:IS_16\n" "m.c int_size:IS_32\n" "m.d int_size:IS_32\n" "m.e int_size:IS_64\n")
        self.assertEqual(members(text, "m"), [
            "int8_t a = 0;", "int16_t b = 0;", "int32_t c = 0;", "int32_t d = 0;", "int64_t e = 0;"])
        self.assertEqual(field_list(text, "m"), [
            "a = 1:ZIGZAG", "b = 2:ZIGZAG", "c = 3:ZIGZAG", "d = 4:ZIGZAG", "e = 5:ZIGZAG"])

    def test_int_size_on_repeated_sint(self):
        text = header("message m { repeated sint32 a = 1; }", "m.a max_count:4 int_size:IS_8\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int8_t, 4> a = {};"])
        self.assertEqual(field_list(text, "m"), ["a = 1:ZIGZAG"])

    def test_int_size_on_repeated_field(self):
        text = header("message m { repeated int32 a = 1; }", "m.a max_count:4 int_size:IS_16\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int16_t, 4> a = {};"])

    def test_repeated_element_types(self):
        text = header("""
            enum kind { KIND_A = 0; }
            message inner { int32 x = 1; }
            message m { repeated string a = 1; repeated inner b = 2; repeated kind c = 3; repeated bytes d = 4; }
            """, "m.* max_count:2\n")
        self.assertEqual(members(text, "m"), [
            "pb::repeated<std::string_view, 2> a = {};", "pb::repeated<inner, 2> b = {};", "pb::repeated<kind, 2> c = {};",
            "pb::repeated<std::span<const uint8_t>, 2> d = {};"])

    def test_pointer_repeated(self):
        text = header("""
            enum kind { KIND_A = 0; }
            message inner { int32 x = 1; }
            message m {
              repeated int32 a = 1; repeated inner b = 2; repeated kind c = 3; repeated string d = 4;
              repeated bytes e = 5; repeated sint32 f = 6;
            }
            """, "m.* type:FT_POINTER\nm.f int_size:IS_16\n")
        self.assertEqual(members(text, "m"), [
            "std::span<const int32_t> a = {};", "std::span<const inner> b = {};", "std::span<const kind> c = {};",
            "std::span<const std::string_view> d = {};", "std::span<const std::span<const uint8_t>> e = {};",
            "std::span<const int16_t> f = {};"])
        self.assertEqual(field_list(text, "m"), ["a = 1", "b = 2", "c = 3", "d = 4", "e = 5", "f = 6:ZIGZAG"])

    def test_pointer_bytes_and_string(self):
        text = header("message m { bytes a = 1; string b = 2; bytes c = 3; string d = 4; }",
                      "m.* max_size:8\nm.a type:FT_POINTER\nm.b type:FT_POINTER\n")
        self.assertEqual(members(text, "m"), [
            "std::span<const uint8_t> a = {};", "std::string_view b = {};", "pb::bytes<8> c = {};", "pb::string<7> d = {};"])

    def test_type_static_and_default(self):
        text = header("message m { repeated int32 a = 1; repeated int32 b = 2; }",
                      "m.* type:FT_POINTER\nm.a max_count:2 type:FT_STATIC\nm.b max_count:3 type:FT_DEFAULT\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 2> a = {};", "pb::repeated<int32_t, 3> b = {};"])

    def test_pointer_on_a_repeated_unsigned_byte_is_an_error(self):
        self.assertIn("a.proto: m.a: int_size:IS_8 on a repeated unsigned field gives a bytes field",
                      error(PROTO3 + "message m { repeated uint32 a = 1; }", "m.a int_size:IS_8 type:FT_POINTER\n"))

    def test_wildcards(self):
        proto = "message m { repeated int32 a = 1; repeated int32 b = 2; }"
        self.assertEqual(members(header(proto, "* max_count:8\n"), "m"),
                         ["pb::repeated<int32_t, 8> a = {};", "pb::repeated<int32_t, 8> b = {};"])
        self.assertEqual(members(header(proto, "m.? max_count:5\n"), "m"),
                         ["pb::repeated<int32_t, 5> a = {};", "pb::repeated<int32_t, 5> b = {};"])

    def test_last_line_wins(self):
        proto = "message m { repeated int32 a = 1; repeated int32 b = 2; }"
        self.assertEqual(members(header(proto, "* max_count:8\nm.a max_count:2\n"), "m"),
                         ["pb::repeated<int32_t, 2> a = {};", "pb::repeated<int32_t, 8> b = {};"])
        self.assertEqual(members(header(proto, "m.a max_count:2\n* max_count:8\n"), "m"),
                         ["pb::repeated<int32_t, 8> a = {};", "pb::repeated<int32_t, 8> b = {};"])

    def test_options_of_different_lines_merge(self):
        text = header("message m { repeated int32 a = 1; }", "* max_count:8\nm.a fixed_count:true\n")
        self.assertEqual(members(text, "m"), ["std::array<int32_t, 8> a = {};"])

    def test_name_with_and_without_package(self):
        proto = "package p.q; message m { repeated int32 a = 1; repeated int32 b = 2; }"
        text = header(proto, "p.q.m.a max_count:2\nm.b max_count:3\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 2> a = {};", "pb::repeated<int32_t, 3> b = {};"])

    def test_comments_blank_lines_and_spaces(self):
        text = header("message m { repeated int32 a = 1; repeated int32 b = 2; }",
                      "# a comment\n\n// one more\nm.a   max_count: 4   # at the end\n\tm.b max_count:5 // end\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<int32_t, 4> a = {};", "pb::repeated<int32_t, 5> b = {};"])

    def test_options_file_next_to_a_proto_in_a_sub_folder(self):
        result = run({"sub/b.proto": 'syntax = "proto3"; message m { repeated int32 a = 1; }',
                      "sub/b.options": "m.a max_count:7\n"})
        self.assertEqual(result.rc, 0, result.stderr)
