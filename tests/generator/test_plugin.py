#!/usr/bin/env python3
"""Tests of tools/protoc-gen-micropb.py. Each test runs the plugin through protoc.

    python tests/generator/test_plugin.py                 run the tests
    python tests/generator/test_plugin.py --check-tools   return 0 when protoc and protobuf are available

protoc comes from the environment variable PROTOC, from PATH, or from the Python module grpc_tools.
MICROPB_UPDATE_GENERATED=1 writes the checked-in headers again.
"""

import importlib.util
import os
import shutil
import stat
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path
from typing import NamedTuple

REPO = Path(__file__).resolve().parents[2]
PLUGIN = REPO / "tools" / "protoc-gen-micropb.py"


def protoc_command():
    """The command that starts protoc, or None."""
    if os.environ.get("PROTOC"):
        return [os.environ["PROTOC"]]
    if shutil.which("protoc"):
        return ["protoc"]
    if importlib.util.find_spec("grpc_tools"):
        return [sys.executable, "-m", "grpc_tools.protoc"]
    return None


def tools_available():
    return protoc_command() is not None and importlib.util.find_spec("google.protobuf") is not None


class Result(NamedTuple):
    rc: int
    headers: dict  # relative path -> text
    stderr: str


def make_starter(folder):
    """protoc needs an executable file. This one starts the plugin with the Python of the tests."""
    if os.name == "nt":
        starter = Path(folder) / "protoc-gen-micropb.bat"
        starter.write_text(f'@"{sys.executable}" "{PLUGIN}" %*\n')
    else:
        starter = Path(folder) / "protoc-gen-micropb"
        starter.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{PLUGIN}" "$@"\n')
        starter.chmod(starter.stat().st_mode | stat.S_IXUSR)
    return starter


def run_protoc(cwd, protos, out, *args):
    """Runs protoc with the plugin in `cwd`. Returns the return code and stderr."""
    if not any(arg.startswith("-I") for arg in args):
        args = ("-I.",) + args  # the default of protoc. The grpc_tools module does not have it.
    with tempfile.TemporaryDirectory() as bin_dir:
        command = protoc_command() + [f"--plugin=protoc-gen-micropb={make_starter(bin_dir)}", f"--micropb_out={out}"]
        done = subprocess.run(command + list(args) + list(protos), cwd=cwd, capture_output=True, text=True)
    return done.returncode, done.stderr


def run(files, *args, protos=None):
    """Writes `files` (name -> text) to a new folder and compiles `protos` (default: each .proto file) there."""
    with tempfile.TemporaryDirectory() as work:
        for name, text in files.items():
            path = Path(work) / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(textwrap.dedent(text))
        out = Path(work) / "out"
        out.mkdir()
        protos = protos or [name for name in files if name.endswith(".proto")]
        rc, stderr = run_protoc(work, protos, out, *args)
        headers = {p.relative_to(out).as_posix(): p.read_text() for p in out.rglob("*") if p.is_file()}
    return Result(rc, headers, stderr)


def header(proto, options=None, *args):
    """The header text for one proto3 file `a.proto` with the body `proto`."""
    files = {"a.proto": 'syntax = "proto3";\n' + textwrap.dedent(proto)}
    if options is not None:
        files["a.options"] = options
    result = run(files, *args)
    assert result.rc == 0, result.stderr
    return result.headers["a.pb.hpp"]


def error(proto, options=None):
    """The error text of protoc for one file `a.proto` with the complete text `proto`. No header is written."""
    files = {"a.proto": proto}
    if options is not None:
        files["a.options"] = options
    result = run(files)
    assert result.rc != 0, "protoc did not fail"
    assert not result.headers, "a header was written"
    return result.stderr


class CoreTest(unittest.TestCase):
    def test_complete_header(self):
        text = header("""
            package app.link;
            enum Mode { MODE_OFF = 0; MODE_ON = 1; }
            message Inner { int32 x = 1; }
            message Outer { Inner child = 1; Mode mode = 2; string name = 3; bytes data = 4; sint32 delta = 5; }
            """)
        self.assertEqual(text, textwrap.dedent("""\
            // Generated by protoc-gen-micropb from a.proto. Do not edit.
            #pragma once

            #include <cstdint>
            #include <span>
            #include <string_view>

            #include <micropb/types.hpp>

            namespace app::link {

            enum class Mode : std::int32_t {
                OFF = 0,
                ON = 1,
            };

            struct Inner {
                std::int32_t x;
            };

            struct Outer {
                Inner child;
                Mode mode;
                std::string_view name;
                std::span<const std::uint8_t> data;
                pb::sint32 delta;
            };

            } // namespace app::link
            """))

    def test_scalar_types(self):
        text = header("""
            message m {
              int32 a = 1; int64 b = 2; uint32 c = 3; uint64 d = 4; sint32 e = 5; sint64 f = 6; bool g = 7;
              float h = 8; double i = 9; fixed32 j = 10; fixed64 k = 11; sfixed32 l = 12; sfixed64 n = 13;
            }
            """)
        members = [line.strip() for line in text.split("struct m {\n")[1].split("};")[0].splitlines()]
        self.assertEqual(members, [
            "std::int32_t a;", "std::int64_t b;", "std::uint32_t c;", "std::uint64_t d;", "pb::sint32 e;",
            "pb::sint64 f;", "bool g;", "float h;", "double i;", "pb::fixed32 j;", "pb::fixed64 k;",
            "pb::sfixed32 l;", "pb::sfixed64 n;"])

    def test_no_package_has_no_namespace(self):
        text = header("message m { bool a = 1; }")
        self.assertNotIn("namespace", text)
        self.assertTrue(text.endswith("struct m {\n    bool a;\n};\n"))

    def test_includes_only_what_the_header_uses(self):
        text = header("message m { bool a = 1; }")
        self.assertNotIn("#include", text)

    def test_empty_message(self):
        self.assertIn("struct m {};\n", header("message m {}"))

    def test_enum_prefix_from_camel_case_name(self):
        text = header("enum RxMode { RX_MODE_FIXED = 0; RX_MODE_VARIABLE = -1; }")
        self.assertIn("enum class RxMode : std::int32_t {\n    FIXED = 0,\n    VARIABLE = -1,\n};", text)

    def test_enum_keeps_names_when_a_value_has_no_prefix(self):
        text = header("enum color { COLOR_RED = 0; BLUE = 1; }")
        self.assertIn("    COLOR_RED = 0,\n    BLUE = 1,\n", text)

    def test_enum_keeps_names_when_the_rest_is_not_an_identifier(self):
        text = header("enum size { SIZE_8 = 0; SIZE_16 = 1; }")
        self.assertIn("    SIZE_8 = 0,\n    SIZE_16 = 1,\n", text)

    def test_output_is_next_to_the_proto_path(self):
        result = run({"sub/dir/b.proto": 'syntax = "proto3"; message m {}'})
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(list(result.headers), ["sub/dir/b.pb.hpp"])
        self.assertTrue(result.headers["sub/dir/b.pb.hpp"].startswith(
            "// Generated by protoc-gen-micropb from sub/dir/b.proto. Do not edit.\n"))


def members(text, name):
    """The member lines of the struct `name` in the header `text`."""
    return [line.strip() for line in text.split(f"struct {name} {{\n")[1].split("};")[0].splitlines()]


def definitions(text):
    """The names of the enums and structs of the header `text`, in order."""
    return [line.split()[-2 if line.endswith("{};") else -4 if ":" in line else -2]
            for line in text.splitlines() if line.startswith(("struct ", "enum class "))]


class OptionsTest(unittest.TestCase):
    def test_max_count(self):
        text = header("message m { repeated int32 a = 1; }", "m.a max_count:4\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<std::int32_t, 4> a;"])

    def test_fixed_count(self):
        text = header("message m { repeated float a = 1; }", "m.a max_count:3 fixed_count:true\n")
        self.assertEqual(members(text, "m"), ["std::array<float, 3> a;"])
        self.assertIn("#include <array>\n", text)

    def test_fixed_count_false(self):
        text = header("message m { repeated float a = 1; }", "m.a max_count:3 fixed_count:false\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<float, 3> a;"])

    def test_max_size_and_fixed_length(self):
        text = header("message m { bytes a = 1; bytes b = 2; bytes c = 3; }",
                      "m.a max_size:16\nm.b max_size:6 fixed_length:true\n")
        self.assertEqual(members(text, "m"), [
            "pb::repeated<std::uint8_t, 16> a;", "std::array<std::uint8_t, 6> b;", "std::span<const std::uint8_t> c;"])

    def test_int_size(self):
        text = header("message m { int32 a = 1; uint32 b = 2; int64 c = 3; uint64 d = 4; }",
                      "m.a int_size:IS_8\nm.b int_size:IS_16\nm.c int_size:IS_32\nm.d int_size:IS_64\n")
        self.assertEqual(members(text, "m"),
                         ["std::int8_t a;", "std::uint16_t b;", "std::int32_t c;", "std::uint64_t d;"])

    def test_int_size_on_repeated_field(self):
        text = header("message m { repeated int32 a = 1; }", "m.a max_count:4 int_size:IS_16\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<std::int16_t, 4> a;"])

    def test_repeated_element_types(self):
        text = header("""
            enum kind { KIND_A = 0; }
            message inner { int32 x = 1; }
            message m { repeated string a = 1; repeated inner b = 2; repeated kind c = 3; repeated bytes d = 4; }
            """, "m.* max_count:2\n")
        self.assertEqual(members(text, "m"), [
            "pb::repeated<std::string_view, 2> a;", "pb::repeated<inner, 2> b;", "pb::repeated<kind, 2> c;",
            "pb::repeated<std::span<const std::uint8_t>, 2> d;"])

    def test_wildcards(self):
        proto = "message m { repeated int32 a = 1; repeated int32 b = 2; }"
        self.assertEqual(members(header(proto, "* max_count:8\n"), "m"),
                         ["pb::repeated<std::int32_t, 8> a;", "pb::repeated<std::int32_t, 8> b;"])
        self.assertEqual(members(header(proto, "m.? max_count:5\n"), "m"),
                         ["pb::repeated<std::int32_t, 5> a;", "pb::repeated<std::int32_t, 5> b;"])

    def test_last_line_wins(self):
        proto = "message m { repeated int32 a = 1; repeated int32 b = 2; }"
        self.assertEqual(members(header(proto, "* max_count:8\nm.a max_count:2\n"), "m"),
                         ["pb::repeated<std::int32_t, 2> a;", "pb::repeated<std::int32_t, 8> b;"])
        self.assertEqual(members(header(proto, "m.a max_count:2\n* max_count:8\n"), "m"),
                         ["pb::repeated<std::int32_t, 8> a;", "pb::repeated<std::int32_t, 8> b;"])

    def test_options_of_different_lines_merge(self):
        text = header("message m { repeated int32 a = 1; }", "* max_count:8\nm.a fixed_count:true\n")
        self.assertEqual(members(text, "m"), ["std::array<std::int32_t, 8> a;"])

    def test_name_with_and_without_package(self):
        proto = "package p.q; message m { repeated int32 a = 1; repeated int32 b = 2; }"
        text = header(proto, "p.q.m.a max_count:2\nm.b max_count:3\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<std::int32_t, 2> a;", "pb::repeated<std::int32_t, 3> b;"])

    def test_comments_blank_lines_and_spaces(self):
        text = header("message m { repeated int32 a = 1; repeated int32 b = 2; }",
                      "# a comment\n\n// one more\nm.a   max_count: 4   # at the end\n\tm.b max_count:5 // end\n")
        self.assertEqual(members(text, "m"), ["pb::repeated<std::int32_t, 4> a;", "pb::repeated<std::int32_t, 5> b;"])

    def test_options_file_next_to_a_proto_in_a_sub_folder(self):
        result = run({"sub/b.proto": 'syntax = "proto3"; message m { repeated int32 a = 1; }',
                      "sub/b.options": "m.a max_count:7\n"})
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(members(result.headers["sub/b.pb.hpp"], "m"), ["pb::repeated<std::int32_t, 7> a;"])

    def test_options_dir_parameter(self):
        result = run({"proto/a.proto": 'syntax = "proto3"; message m { repeated int32 a = 1; }',
                      "opts/a.options": "m.a max_count:9\n"},
                     "-Iproto", "--micropb_opt=options_dir=opts", protos=["proto/a.proto"])
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(members(result.headers["a.pb.hpp"], "m"), ["pb::repeated<std::int32_t, 9> a;"])


class StructureTest(unittest.TestCase):
    def test_optional(self):
        text = header("message inner { int32 x = 1; } message m { optional int32 a = 1; optional inner b = 2; }")
        self.assertEqual(members(text, "m"), ["std::optional<std::int32_t> a;", "std::optional<inner> b;"])
        self.assertIn("#include <optional>\n", text)

    def test_oneof_with_consecutive_numbers(self):
        text = header("""
            message a { int32 x = 1; }
            message b { int32 x = 1; }
            message m { uint32 id = 1; oneof payload { a first = 2; b second = 3; } bool last = 4; }
            """)
        self.assertEqual(members(text, "m"),
                         ["std::uint32_t id;", "std::variant<std::monostate, a, b> payload;", "bool last;"])
        self.assertIn("#include <variant>\n", text)

    def test_oneof_with_other_numbers(self):
        text = header("""
            message m { uint32 id = 1; oneof payload { int32 first = 5; string second = 7; } bool last = 8; }
            """)
        self.assertEqual(members(text, "m"), [
            "std::uint32_t id;",
            "[[= pb::oneof_tags<5, 7>{}]] std::variant<std::monostate, std::int32_t, std::string_view> payload;",
            "bool last;"])

    def test_oneof_next_to_an_optional_field(self):
        text = header("message m { optional bool a = 1; oneof v { int32 b = 2; bool c = 3; } optional bool d = 4; }")
        self.assertEqual(members(text, "m"), [
            "std::optional<bool> a;", "std::variant<std::monostate, std::int32_t, bool> v;", "std::optional<bool> d;"])

    def test_tag_only_where_the_numbers_have_a_gap(self):
        text = header("message m { int32 a = 3; int32 b = 4; int32 c = 10; int32 d = 11; int32 e = 5; }")
        self.assertEqual(members(text, "m"), [
            "[[= pb::tag{3}]] std::int32_t a;", "std::int32_t b;", "[[= pb::tag{10}]] std::int32_t c;",
            "std::int32_t d;", "[[= pb::tag{5}]] std::int32_t e;"])
        self.assertIn("#include <micropb/types.hpp>\n", text)

    def test_nested_types_are_flattened(self):
        text = header("""
            message Outer {
              message Inner { message Deep { int32 x = 1; } Deep deep = 1; }
              enum Kind { KIND_A = 0; KIND_B = 1; }
              Inner inner = 1;
              Kind kind = 2;
            }
            """)
        self.assertEqual(definitions(text), ["Outer_Kind", "Outer_Inner_Deep", "Outer_Inner", "Outer"])
        self.assertIn("enum class Outer_Kind : std::int32_t {\n    A = 0,\n    B = 1,\n};", text)
        self.assertEqual(members(text, "Outer"), ["Outer_Inner inner;", "Outer_Kind kind;"])
        self.assertEqual(members(text, "Outer_Inner"), ["Outer_Inner_Deep deep;"])

    def test_a_struct_comes_after_the_structs_that_it_contains(self):
        text = header("""
            message a { b child = 1; }
            message b { optional c child = 1; }
            message c {}
            message d {}
            """)
        self.assertEqual(definitions(text), ["c", "b", "a", "d"])

    def test_nested_type_used_by_an_earlier_message(self):
        text = header("""
            message user { holder.item it = 1; }
            message holder { message item { int32 x = 1; } user u = 1; }
            """)
        self.assertEqual(definitions(text), ["holder_item", "user", "holder"])

    def test_import_from_another_package(self):
        result = run({
            "a.proto": """
                syntax = "proto3";
                package app;
                import "lib/b.proto";
                message m { lib.types.point p = 1; lib.types.kind k = 2; sint32 d = 3; }
                """,
            "lib/b.proto": """
                syntax = "proto3";
                package lib.types;
                enum kind { KIND_A = 0; }
                message point { int32 x = 1; }
                """})
        self.assertEqual(result.rc, 0, result.stderr)
        text = result.headers["a.pb.hpp"]
        self.assertEqual(members(text, "m"), ["::lib::types::point p;", "::lib::types::kind k;", "pb::sint32 d;"])
        self.assertIn('#pragma once\n\n#include <micropb/types.hpp>\n\n#include "lib/b.pb.hpp"\n\nnamespace app {',
                      text)
        self.assertIn("struct point {", result.headers["lib/b.pb.hpp"])

    def test_import_from_the_same_package(self):
        result = run({
            "a.proto": 'syntax = "proto3"; package app; import "b.proto"; message m { point p = 1; }',
            "b.proto": 'syntax = "proto3"; package app; message point { int32 x = 1; }'})
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertEqual(members(result.headers["a.pb.hpp"], "m"), ["point p;"])
        self.assertIn('#pragma once\n\n#include "b.pb.hpp"\n\nnamespace app {', result.headers["a.pb.hpp"])

    def test_import_that_is_not_used_gives_no_include(self):
        result = run({
            "a.proto": 'syntax = "proto3"; import "b.proto"; message m { bool x = 1; }',
            "b.proto": 'syntax = "proto3"; message point { int32 x = 1; }'}, protos=["a.proto"])
        self.assertEqual(result.rc, 0, result.stderr)
        self.assertNotIn("#include", result.headers["a.pb.hpp"])

    def test_keyword_names_get_a_suffix(self):
        text = header("""
            enum mode { auto = 0; MANUAL = 1; }
            message union { int32 class = 1; bool default = 2; mode namespace = 3; }
            """)
        self.assertIn("    auto_ = 0,\n    MANUAL = 1,\n", text)
        self.assertEqual(members(text, "union_"), ["std::int32_t class_;", "bool default_;", "mode namespace_;"])

    def test_field_name_equal_to_a_type_name(self):
        text = header("package p; message inner { int32 x = 1; } message m { inner inner = 1; inner other = 2; }")
        self.assertEqual(members(text, "m"), ["::p::inner inner;", "::p::inner other;"])
        text = header("message inner { int32 x = 1; } message m { inner inner = 1; }")
        self.assertEqual(members(text, "m"), ["::inner inner;"])

    def test_cstdint_is_not_included_for_a_name_that_contains_int(self):
        self.assertNotIn("#include", header("message point { bool int_flag = 1; }"))

    def test_service_is_ignored(self):
        text = header("message m { bool a = 1; } service control { rpc run(m) returns (m); }")
        self.assertEqual(definitions(text), ["m"])
        self.assertNotIn("control", text)

    def test_extend_block_is_ignored(self):
        text = header("""
            import "google/protobuf/descriptor.proto";
            extend google.protobuf.FieldOptions { int32 unit = 50000; }
            message m { bool a = 1 [(unit) = 3]; }
            """)
        self.assertEqual(members(text, "m"), ["bool a;"])
        self.assertNotIn("#include", text)


