#!/usr/bin/env python3
"""protoc plugin: writes C++26 structs for micropb from a proto3 file.

    protoc --plugin=protoc-gen-micropb=tools/protoc-gen-micropb.py --micropb_out=gen app.proto

The output is gen/app.pb.hpp. It needs Python 3 and the Python package protobuf.
"""

import re
import sys

from google.protobuf.compiler import plugin_pb2
from google.protobuf.descriptor_pb2 import FieldDescriptorProto as Field


class Error(Exception):
    """A problem in the input. protoc prints the text and stops."""


SCALARS = {
    Field.TYPE_BOOL: "bool",
    Field.TYPE_INT32: "std::int32_t",
    Field.TYPE_INT64: "std::int64_t",
    Field.TYPE_UINT32: "std::uint32_t",
    Field.TYPE_UINT64: "std::uint64_t",
    Field.TYPE_SINT32: "pb::sint32",
    Field.TYPE_SINT64: "pb::sint64",
    Field.TYPE_FIXED32: "pb::fixed32",
    Field.TYPE_FIXED64: "pb::fixed64",
    Field.TYPE_SFIXED32: "pb::sfixed32",
    Field.TYPE_SFIXED64: "pb::sfixed64",
    Field.TYPE_FLOAT: "float",
    Field.TYPE_DOUBLE: "double",
    Field.TYPE_STRING: "std::string_view",
    Field.TYPE_BYTES: "std::span<const std::uint8_t>",
}

# The headers that the generated text can need, each with the text that shows the need.
INCLUDES = [
    ("<array>", "std::array<"),
    ("<cstdint>", "int"),
    ("<optional>", "std::optional<"),
    ("<span>", "std::span<"),
    ("<string_view>", "std::string_view"),
    ("<variant>", "std::variant<"),
]


class Type:
    """A message or an enum of a .proto file."""

    def __init__(self, package, path, desc):
        self.package = package
        self.desc = desc
        self.name = "_".join(path)


def types_of(file):
    """The enums and the messages of `file`, each in the order of the file."""
    enums = [Type(file.package, [desc.name], desc) for desc in file.enum_type]
    messages = [Type(file.package, [desc.name], desc) for desc in file.message_type]
    return enums, messages


def screaming_case(name):
    """`RxMode` and `rx_mode` give `RX_MODE`."""
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return name.upper()


def enum_text(enum):
    """The definition of an enum. The values lose the prefix `<ENUM NAME>_` when each value has it."""
    prefix = screaming_case(enum.desc.name) + "_"
    names = [value.name for value in enum.desc.value]
    if all(name.upper().startswith(prefix) and name[len(prefix):].isidentifier() for name in names):
        names = [name[len(prefix):] for name in names]

    lines = [f"enum class {enum.name} : std::int32_t {{"]
    lines += [f"    {name} = {value.number}," for name, value in zip(names, enum.desc.value)]
    return "\n".join(lines + ["};"])


def value_type(field):
    """The C++ type of one value of `field`."""
    if field.type in (Field.TYPE_MESSAGE, Field.TYPE_ENUM):
        return field.type_name.rsplit(".", 1)[-1]
    return SCALARS[field.type]


def struct_text(message):
    """The definition of the struct of a message."""
    if not message.desc.field:
        return f"struct {message.name} {{}};"

    lines = [f"struct {message.name} {{"]
    lines += [f"    {value_type(field)} {field.name};" for field in message.desc.field]
    return "\n".join(lines + ["};"])


def header_text(file):
    """The complete header for one .proto file."""
    enums, messages = types_of(file)
    blocks = [enum_text(enum) for enum in enums] + [struct_text(message) for message in messages]
    body = "\n\n".join(blocks)

    out = [f"// Generated by protoc-gen-micropb from {file.name}. Do not edit.", "#pragma once", ""]
    includes = [f"#include {name}" for name, mark in INCLUDES if mark in body]
    if includes:
        out += includes + [""]
    if "pb::" in body:
        out += ["#include <micropb/types.hpp>", ""]

    namespace = file.package.replace(".", "::")
    if namespace:
        out += [f"namespace {namespace} {{", "", body, "", f"}} // namespace {namespace}"]
    else:
        out += [body]
    return "\n".join(out) + "\n"


def generate(request):
    """The response of the plugin for `request`."""
    response = plugin_pb2.CodeGeneratorResponse()
    response.supported_features = plugin_pb2.CodeGeneratorResponse.FEATURE_PROTO3_OPTIONAL
    files = {file.name: file for file in request.proto_file}
    try:
        for name in request.file_to_generate:
            text = header_text(files[name])
            response.file.add(name=re.sub(r"\.proto$", "", name) + ".pb.hpp", content=text)
    except Error as error:
        response.Clear()
        response.error = str(error)
    return response


def main():
    request = plugin_pb2.CodeGeneratorRequest.FromString(sys.stdin.buffer.read())
    sys.stdout.buffer.write(generate(request).SerializeToString())


if __name__ == "__main__":
    main()
